function catalogoPerScelta() {
  return {
    categorie: CATEGORIE.filter(c => SCHEDE.some(s => s.categoria === c.id)).map(c => ({ id: c.id, nome: c.nome })),
    schede: SCHEDE.map(s => {
      const top = rischiValutati(s).sort((a, b) => b.r - a.r)[0];
      return {
        id: s.id, nome: s.nome, categoria: s.categoria, pericolosita: s.pericolosita,
        // per il controllo finale di /pos/crea (F-263)
        rischioMax: { rischio: top.rischio, livello: top.livello, r: top.r },
        misure: s.misure.length,
        dpi: [...s.dpi],
        formazione: [...s.formazione],
      };
    }),
    dpi: Object.fromEntries(Object.entries(DPI).map(([k, v]) => [k, v.nome])),
    formazione: { ...FORMAZIONE },
    corsiPerFormazione: { ...CORSI_PER_FORMAZIONE },
    vociVecchie: Object.fromEntries(BY_VOCE_VECCHIA),
    psc: PSC_PAROLE,
  };
}

