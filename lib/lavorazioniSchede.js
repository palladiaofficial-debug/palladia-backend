function livello(r) {
  if (r >= 12) return "Molto alto";
  if (r >= 8) return "Alto";
  if (r >= 4) return "Medio";
  return "Basso";
}

/** Rischi espansi con R = P×D e livello. */
function rischiValutati(scheda) {
  return scheda.rischi.map(([rischio, p, d]) => ({ rischio, p, d, r: p * d, livello: livello(p * d) }));
}

function getScheda(id) {
  return BY_ID.get(id) || null;
}

/** Voce del vecchio catalogo → id della scheda che la sostituisce (o null). */
function schedaPerVoceVecchia(voce) {
  return BY_VOCE_VECCHIA.get(voce) || null;
}

